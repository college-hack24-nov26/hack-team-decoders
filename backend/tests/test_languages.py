"""Language registry — the single source of truth for what the kiosk supports.

The reason this module exists is that four capabilities cover different sets:
Saaras transcribes 23 languages, Bulbul speaks 11, sarvam-translate covers 23,
and our own interface strings cover 2. These tests pin that asymmetry so a
future edit cannot quietly offer a language the kiosk has no voice for.
"""

from __future__ import annotations

import pytest

from app.interview import languages

#: Bulbul v3's documented language list.
_TTS_EXPECTED = {"en", "hi", "bn", "ta", "te", "gu", "kn", "ml", "mr", "pa", "od"}

#: The 22 scheduled languages plus English, which Saaras transcribes.
_STT_EXPECTED_COUNT = 23

#: Languages with interface strings and interview prompts. English and Hindi are
#: hand-written; the rest were generated by scripts/generate_locales.py. Odia is
#: the one gap in Bulbul's set — its generation ran out of Sarvam credits.
_UI_EXPECTED = {"en", "hi", "bn", "mr", "te", "ta", "gu", "kn", "ml", "pa"}


class TestRegistryShape:
    def test_covers_all_scheduled_languages_plus_english(self):
        assert len(languages.LANGUAGES) == _STT_EXPECTED_COUNT

    def test_codes_are_unique(self):
        codes = [lang.code for lang in languages.LANGUAGES]
        assert len(codes) == len(set(codes))

    def test_every_language_has_a_native_name(self):
        """The picker shows this, so a patient who cannot read English finds it."""
        for lang in languages.LANGUAGES:
            assert lang.native_name.strip(), f"{lang.code} has no native name"

    def test_every_language_is_transcribable(self):
        """Saaras covers the whole set; nothing here is speech-unsupported."""
        assert all(lang.stt for lang in languages.LANGUAGES)

    def test_every_language_is_translatable(self):
        """sarvam-translate:v1 covers all 22 scheduled languages plus English."""
        assert all(lang.translate for lang in languages.LANGUAGES)

    def test_bcp47_tags_are_india_scoped(self):
        for lang in languages.LANGUAGES:
            assert lang.bcp47.endswith("-IN"), f"{lang.code} -> {lang.bcp47}"

    def test_full_support_is_only_where_we_have_strings(self):
        """Claiming full support without translated prompts would be a lie."""
        full = {
            lang.code for lang in languages.LANGUAGES if lang.support == languages.SupportLevel.FULL
        }
        assert full == _UI_EXPECTED

    def test_full_support_implies_the_kiosk_can_speak_it(self):
        """Screen text without audio is not full support for a patient who cannot
        read, so every full-support language must also be voiceable."""
        for lang in languages.LANGUAGES:
            if lang.support == languages.SupportLevel.FULL:
                assert lang.tts, f"{lang.code} claims full support but has no voice"


class TestTtsAsymmetry:
    """Bulbul speaks 11 of the 23. Getting this wrong means patient silence."""

    def test_tts_set_matches_bulbul(self):
        assert {lang.code for lang in languages.tts_languages()} == _TTS_EXPECTED

    def test_stt_is_wider_than_tts(self):
        assert len(languages.stt_languages()) > len(languages.tts_languages())

    @pytest.mark.parametrize("code", sorted(_TTS_EXPECTED))
    def test_supported_language_speaks_in_itself(self, code):
        assert languages.tts_language(code) == code

    @pytest.mark.parametrize("code", ["sat", "mni", "ks", "sd", "as", "mai", "doi", "brx"])
    def test_unspoken_language_falls_back_rather_than_going_silent(self, code):
        """Sending sat-IN to Bulbul is rejected; the patient would hear nothing."""
        spoken = languages.tts_language(code)

        assert spoken != code
        assert languages.get(spoken).tts is True, "fallback must be speakable"

    def test_every_fallback_is_itself_speakable(self):
        """A fallback Bulbul also cannot say would just move the failure."""
        for lang in languages.LANGUAGES:
            resolved = languages.tts_language(lang.code)
            assert languages.get(resolved).tts, f"{lang.code} -> {resolved} is not speakable"


class TestCodeResolution:
    @pytest.mark.parametrize(
        ("given", "expected"),
        [("hi", "hi-IN"), ("ta", "ta-IN"), ("sat", "sat-IN"), ("od", "od-IN")],
    )
    def test_short_codes_become_tags(self, given, expected):
        assert languages.to_bcp47(given) == expected

    @pytest.mark.parametrize("given", ["hi-IN", "HI", "hi_IN", " hi "])
    def test_resolution_tolerates_tag_case_and_whitespace(self, given):
        assert languages.get(given).code == "hi"

    def test_unknown_code_defaults_to_english(self):
        """The physician reads English, so an unknown code degrades usefully."""
        assert languages.get("xx").code == "en"

    def test_none_defaults_to_english(self):
        assert languages.get(None).code == "en"

    def test_auto_detect_asks_sarvam_when_code_is_unrecognised(self):
        """Better to let the model identify it than to guess wrong."""
        assert languages.to_bcp47("xx", auto_detect=True) == languages.AUTO_DETECT

    def test_auto_detect_still_honours_a_known_code(self):
        assert languages.to_bcp47("bn", auto_detect=True) == "bn-IN"

    @pytest.mark.parametrize(
        ("tag", "expected"), [("hi-IN", "hi"), ("sat-IN", "sat"), ("EN-in", "en")]
    )
    def test_returned_tags_map_back_to_short_codes(self, tag, expected):
        assert languages.from_bcp47(tag) == expected

    def test_unknown_returned_tag_uses_the_fallback(self):
        assert languages.from_bcp47("zz-ZZ", fallback="hi") == "hi"

    def test_is_supported_rejects_unknown_and_empty(self):
        assert languages.is_supported("ta") is True
        assert languages.is_supported("xx") is False
        assert languages.is_supported(None) is False


class TestSummaryTranslationGating:
    """Which transcripts get translated before reaching the LLM."""

    @pytest.mark.parametrize("code", ["en", "hi"])
    def test_english_and_hindi_are_left_alone(self, code):
        """The summariser handles both; translating would discard the patient's
        own words for no gain."""
        assert languages.needs_translation_for_summary(code) is False

    @pytest.mark.parametrize("code", ["ta", "bn", "sat", "mni", "brx", "doi", "ur"])
    def test_everything_else_is_translated(self, code):
        assert languages.needs_translation_for_summary(code) is True

    def test_unknown_code_is_treated_as_english(self):
        assert languages.needs_translation_for_summary("xx") is False


class TestApiPayload:
    def test_payload_covers_every_language(self):
        assert len(languages.as_api_payload()) == len(languages.LANGUAGES)

    def test_payload_reports_the_audio_language_actually_used(self):
        payload = {entry["code"]: entry for entry in languages.as_api_payload()}

        assert payload["ta"]["audioLanguage"] == "ta"
        # Santali has speech input but no Bulbul voice.
        assert payload["sat"]["audioOutput"] is False
        assert payload["sat"]["audioLanguage"] != "sat"

    def test_payload_does_not_overstate_interface_support(self):
        translated = {
            entry["code"] for entry in languages.as_api_payload() if entry["interfaceTranslated"]
        }
        assert translated == _UI_EXPECTED
